export function t(locale: CommunityLocale, key: MessageKey): string {
  return messages[locale][key] ?? messages.es[key];
}

export function getSkillLabelLocalized(
  level: string,
  locale: CommunityLocale
): string {
  const map: Record<string, MessageKey> = {
    beginner: "skillBeginner",
    intermediate: "skillIntermediate",
    advanced: "skillAdvanced",
    expert: "skillExpert",
  };
  const key = map[level];
  return key ? t(locale, key) : level;
}

export function getDayLabels(locale: CommunityLocale) {
  return [
    { key: "mon", label: t(locale, "mon") },
    { key: "tue", label: t(locale, "tue") },
    { key: "wed", label: t(locale, "wed") },
    { key: "thu", label: t(locale, "thu") },
    { key: "fri", label: t(locale, "fri") },
    { key: "sat", label: t(locale, "sat") },
    { key: "sun", label: t(locale, "sun") },
  ] as const;
}

export function getHourLabels(locale: CommunityLocale) {
  return AVAILABILITY_HOURS.map((hour) => ({
    key: String(hour),
    label: formatAvailabilityHour(hour, locale),
  }));
}

