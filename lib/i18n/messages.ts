export function t(locale: CommunityLocale, key: MessageKey): string {
  return messages[locale][key] ?? messages.es[key];
}

export function getSkillLabelLocalized(
  level: string,
  locale: CommunityLocale
): string {
  const map: Record<string, MessageKey> = {
    beginner: "skillBeginner",
    intermediate: "skillIntermediate",
    advanced: "skillAdvanced",
    expert: "skillExpert",
  };
  const key = map[level];
  return key ? t(locale, key) : level;
}

